#!/usr/bin/env python3
"""Generate anon/dict_gen.go (tag -> VR) from pydicom's copy of the DICOM data dictionary.

    pip install pydicom
    python3 gen/gendict.py > anon/dict_gen.go && gofmt -w anon/dict_gen.go
"""
import pydicom
from pydicom._dicom_dict import DicomDictionary

print("// Code generated by gen/gendict.py from the DICOM data dictionary (pydicom %s). DO NOT EDIT." % pydicom.__version__)
print()
print("package anon")
print()
print("// dictVR maps a standard tag (group<<16 | element) to its VR. Ambiguous VRs keep the first choice.")
print("var dictVR = map[uint32]string{")
for tag in sorted(DicomDictionary):
    vr = DicomDictionary[tag][0].split(" or ")[0]
    if vr == "NONE":
        continue
    print("\t0x%08X: \"%s\"," % (tag, vr))
print("}")
